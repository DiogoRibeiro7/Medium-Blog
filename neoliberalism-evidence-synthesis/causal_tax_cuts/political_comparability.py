"""Audit political donor comparability without fitting a causal effect.

Input files are generated by the verified DPI2023 and Hope-Limberg
donor-risk-set workflows. All covariates come strictly from t-5 through
t-1, and the inherited donor risk sets are never modified.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path
from statistics import fmean
from typing import Any

MAX_HORIZON = 5
HISTORY = 5
ORIENTATIONS = frozenset({"left", "center", "right"})


@dataclass(frozen=True, slots=True)
class PoliticalYear:
    """One archived DPI observation with explicit missingness."""

    country: str
    year: int
    executive_orientation: str | None
    checks: float | None
    electoral_competitiveness: float | None


@dataclass(frozen=True, slots=True)
class DonorExposure:
    """An eligible donor's preexisting future-exposure censoring rule."""

    country: str
    reform_year: int
    donor: str
    first_censored_horizon: int | None


@dataclass(frozen=True, slots=True)
class PairComparison:
    """Pre-reform political differences for one inherited donor-event pair."""

    country: str
    reform_year: int
    donor: str
    first_censored_horizon: int | None
    both_full_pre5: bool
    same_orientation_t_minus_1: bool | None
    same_orientation_all_five_years: bool | None
    same_eiec_t_minus_1: bool | None
    abs_checks_five_year_mean_gap: float | None


@dataclass(frozen=True, slots=True)
class EventHorizon:
    """Reform-level comparability at a horizon, without re-matching donors."""

    country: str
    reform_year: int
    horizon: int
    donors_at_risk: int
    comparable_donors: int
    same_orientation_count: int
    same_orientation_path_count: int
    same_eiec_count: int
    mean_abs_checks_gap: float | None


def _read_rows(path: Path, required: frozenset[str]) -> list[dict[str, str]]:
    """Read a validated CSV: reject incomplete schemas and empty files."""
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None or not required.issubset(reader.fieldnames):
            raise ValueError(f"Unexpected columns in {path.name}")
        rows = list(reader)
    if not rows:
        raise ValueError(f"Empty source {path.name}")
    return rows


def _numeric(raw: str, name: str) -> float | None:
    """Parse an observed number, preserving empty values as missing."""
    if raw == "":
        return None
    try:
        result = float(raw)
    except ValueError as exc:
        raise ValueError(f"Invalid {name}: {raw!r}") from exc
    if not math.isfinite(result):
        raise ValueError(f"Non-finite {name}")
    return result


def load_political_years(path: Path) -> dict[tuple[str, int], PoliticalYear]:
    """Load the exact DPI-derived panel; do not treat unknown as observed."""
    required = frozenset(
        {
            "country",
            "year",
            "executive_orientation",
            "orientation_status",
            "checks",
            "electoral_competitiveness",
        }
    )
    records: dict[tuple[str, int], PoliticalYear] = {}
    for row in _read_rows(path, required):
        country = row["country"]
        year = int(row["year"])
        orientation = row["executive_orientation"] or None
        status = row["orientation_status"]
        if (orientation is not None and orientation not in ORIENTATIONS) or (
            (status == "known") != (orientation is not None)
        ):
            raise ValueError(f"Inconsistent DPI orientation {country} {year}")
        if status not in {
            "known",
            "unknown",
            "not_applicable",
            "missing",
            "out_of_source_period",
            "not_in_source",
        }:
            raise ValueError(f"Unknown DPI missingness status {status}")
        key = (country, year)
        if key in records:
            raise ValueError(f"Duplicate political country-year: {key}")
        records[key] = PoliticalYear(
            country,
            year,
            orientation,
            _numeric(row["checks"], "checks"),
            _numeric(row["electoral_competitiveness"], "eiec"),
        )
    return records


def load_donor_exposures(path: Path) -> list[DonorExposure]:
    """Load existing donor-event IDs and unchanged censoring horizons."""
    required = frozenset(
        {
            "country",
            "reform_year",
            "donor",
            "first_censored_horizon",
        }
    )
    items: list[DonorExposure] = []
    seen: set[tuple[str, int, str]] = set()
    for row in _read_rows(path, required):
        year = int(row["reform_year"])
        country, donor = row["country"], row["donor"]
        key = (country, year, donor)
        if country == donor or key in seen:
            raise ValueError(f"Invalid or duplicate donor-reform pair: {key}")
        seen.add(key)
        raw = row["first_censored_horizon"]
        censoring = int(raw) if raw else None
        if censoring is not None and not 0 <= censoring <= MAX_HORIZON:
            raise ValueError(f"Invalid censoring horizon: {censoring}")
        items.append(DonorExposure(country, year, donor, censoring))
    return sorted(items, key=lambda p: (p.reform_year, p.country, p.donor))


def _history(
    records: dict[tuple[str, int], PoliticalYear], country: str, year: int
) -> tuple[PoliticalYear, ...] | None:
    """Return a complete five-year history with no treatment-year leakage."""
    series = tuple(records.get((country, t)) for t in range(year - HISTORY, year))
    if len(series) != HISTORY or any(
        row is None
        or row.executive_orientation is None
        or row.checks is None
        or row.electoral_competitiveness is None
        for row in series
    ):
        return None
    return series  # type: ignore[return-value]


def audit_comparability(
    records: dict[tuple[str, int], PoliticalYear],
    donors: list[DonorExposure],
) -> tuple[list[PairComparison], list[EventHorizon], dict[str, Any]]:
    """Compare political histories on identical inherited donor risk sets.

    EIEC is an electoral category, not a continuous distance. Executive
    orientation is categorical. CHECKS is measured as a mean absolute index
    difference; these comparisons do not determine counterfactual weights.
    """
    if not donors:
        raise ValueError("Donor risk set must not be empty")
    cache: dict[tuple[str, int], tuple[PoliticalYear, ...] | None] = {}

    def past(country: str, year: int) -> tuple[PoliticalYear, ...] | None:
        key = (country, year)
        if key not in cache:
            cache[key] = _history(records, country, year)
        return cache[key]

    comparisons: list[PairComparison] = []
    for pair in donors:
        treated = past(pair.country, pair.reform_year)
        control = past(pair.donor, pair.reform_year)
        if treated is None or control is None:
            comparisons.append(
                PairComparison(
                    pair.country,
                    pair.reform_year,
                    pair.donor,
                    pair.first_censored_horizon,
                    False,
                    None,
                    None,
                    None,
                    None,
                )
            )
            continue
        comparisons.append(
            PairComparison(
                pair.country,
                pair.reform_year,
                pair.donor,
                pair.first_censored_horizon,
                True,
                treated[-1].executive_orientation == control[-1].executive_orientation,
                all(
                    a.executive_orientation == b.executive_orientation
                    for a, b in zip(treated, control, strict=True)
                ),
                treated[-1].electoral_competitiveness
                == control[-1].electoral_competitiveness,
                abs(
                    fmean(float(a.checks) for a in treated)
                    - fmean(float(b.checks) for b in control)
                ),
            )
        )

    groups: dict[tuple[str, int], list[PairComparison]] = defaultdict(list)
    for row in comparisons:
        groups[row.country, row.reform_year].append(row)

    event_horizons: list[EventHorizon] = []
    summary: list[dict[str, int | float | None]] = []
    for horizon in range(-1, MAX_HORIZON + 1):
        subset = [
            row
            for row in comparisons
            if row.first_censored_horizon is None
            or row.first_censored_horizon > horizon
        ]
        comparable = [row for row in subset if row.both_full_pre5]
        for (country, year), event_rows in sorted(
            groups.items(), key=lambda item: (item[0][1], item[0][0])
        ):
            at_risk = [
                row
                for row in event_rows
                if row.first_censored_horizon is None
                or row.first_censored_horizon > horizon
            ]
            complete = [row for row in at_risk if row.both_full_pre5]
            event_horizons.append(
                EventHorizon(
                    country,
                    year,
                    horizon,
                    len(at_risk),
                    len(complete),
                    sum(row.same_orientation_t_minus_1 is True for row in complete),
                    sum(
                        row.same_orientation_all_five_years is True for row in complete
                    ),
                    sum(row.same_eiec_t_minus_1 is True for row in complete),
                    (
                        fmean(
                            float(row.abs_checks_five_year_mean_gap) for row in complete
                        )
                        if complete
                        else None
                    ),
                )
            )
        events_with_coverage = [
            row
            for row in event_horizons
            if row.horizon == horizon and row.comparable_donors > 0
        ]
        summary.append(
            {
                "horizon": horizon,
                "events_total": len(groups),
                "events_with_complete_pairs": len(events_with_coverage),
                "donor_pairs_at_risk": len(subset),
                "complete_treated_donor_pairs": len(comparable),
                "same_orientation_at_t_minus_1": sum(
                    row.same_orientation_t_minus_1 is True for row in comparable
                ),
                "same_orientation_all_five_years": sum(
                    row.same_orientation_all_five_years is True for row in comparable
                ),
                "same_eiec_at_t_minus_1": sum(
                    row.same_eiec_t_minus_1 is True for row in comparable
                ),
                "mean_abs_checks_index_gap_pair_weighted": (
                    fmean(
                        float(row.abs_checks_five_year_mean_gap) for row in comparable
                    )
                    if comparable
                    else None
                ),
                "orientation_agreement_event_weighted": (
                    fmean(
                        row.same_orientation_count / row.comparable_donors
                        for row in events_with_coverage
                    )
                    if events_with_coverage
                    else None
                ),
            }
        )
    return (
        comparisons,
        event_horizons,
        {
            "status": "descriptive_political_comparability_only",
            "by_horizon": summary,
            "n_unique_treated_countries": len({row.country for row in comparisons}),
            "n_baseline_reforms": len(groups),
            "n_initial_pairs": len(comparisons),
            "comparison_definition": (
                "Use t-5 through t-1 only; require all three DPI prehistories. "
                "Treat executive orientation and EIEC as discrete; CHECKS as an index."
            ),
            "limitations": [
                "Donor-event pairs reuse the same countries and are not independent.",
                "Future donor reform exclusions are inherited, not newly justified.",
                "Completeness restriction reduces the descriptive comparison sample.",
                "DPI electoral competitiveness can be nearly constant in OECD democracies.",
                "Agreement on politics does not establish exchangeability or causality.",
                "Only two of twenty reforms had joint WDI donor-hull support at year five.",
            ],
            "inference": "none; no p-values, ATT, causal weights or confidence intervals",
        },
    )


def save_comparability(
    directory: Path,
    comparisons: list[PairComparison],
    horizons: list[EventHorizon],
    report: dict[str, Any],
    *,
    political_controls: Path,
    donor_exposures: Path,
    source_audit: Path,
) -> None:
    """Store deterministic SHA-traceable results and assert sample continuity."""
    prior = json.loads(source_audit.read_text(encoding="utf-8"))
    if prior.get("status") != "pre_tax_cut_political_institutional_coverage_only":
        raise ValueError("Expected the original verified DPI coverage report")
    if (
        report["n_baseline_reforms"] != prior["n_reforms_baseline_eligible"]
        or report["n_initial_pairs"] != prior["n_pre_censor_donor_pairs"]
    ):
        raise ValueError("Political comparability does not match prior donor risk sets")
    for horizon in report["by_horizon"]:
        expected = (
            prior["n_pre_censor_donor_pairs"]
            if horizon["horizon"] == -1
            else prior["n_horizon_five_donor_pairs"]
            if horizon["horizon"] == MAX_HORIZON
            else None
        )
        if expected is not None and horizon["donor_pairs_at_risk"] != expected:
            raise ValueError("Censoring changed inherited donor risk sets")
    result = {
        **report,
        "source_dpi_csv_sha256": prior["source_csv_sha256"],
        "joined_panel_sha256": prior["joined_panel_sha256"],
        "political_controls_sha256": hashlib.sha256(
            political_controls.read_bytes()
        ).hexdigest(),
        "donor_exposures_sha256": hashlib.sha256(
            donor_exposures.read_bytes()
        ).hexdigest(),
        "source_audit_sha256": hashlib.sha256(source_audit.read_bytes()).hexdigest(),
        "license": "DPI2023 CC BY 4.0 — Cruz et al., DOI 10.60966/8tx1xs4i",
    }
    directory.mkdir(parents=True, exist_ok=True)
    for filename, values, row_type in (
        ("political_comparability_pairs.csv", comparisons, PairComparison),
        ("political_comparability_event_horizons.csv", horizons, EventHorizon),
    ):
        with (directory / filename).open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(
                handle, fieldnames=list(row_type.__dataclass_fields__)
            )
            writer.writeheader()
            writer.writerows(asdict(row) for row in values)
    (directory / "political_comparability_audit.json").write_text(
        json.dumps(result, indent=2, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    """Reproduce the political diagnostics from archived CI outputs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--controls", type=Path, required=True)
    parser.add_argument("--donors", type=Path, required=True)
    parser.add_argument("--source-audit", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    pairs, horizons, audit = audit_comparability(
        load_political_years(args.controls), load_donor_exposures(args.donors)
    )
    save_comparability(
        args.output_dir,
        pairs,
        horizons,
        audit,
        political_controls=args.controls,
        donor_exposures=args.donors,
        source_audit=args.source_audit,
    )
    last = audit["by_horizon"][-1]
    print(
        f"At horizon 5: {last['complete_treated_donor_pairs']}/"
        f"{last['donor_pairs_at_risk']} pairs have complete DPI histories; "
        f"{last['same_orientation_at_t_minus_1']} share executive orientation"
    )
    print("CAUTION: descriptive political comparability, not a causal effect")


if __name__ == "__main__":
    main()
