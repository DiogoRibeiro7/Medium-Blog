def change_log_entries(path: Path) -> int:
    """Top-level items of a protocol's ``## Change log`` section."""
    body = path.read_text(encoding="utf-8").split("\n## Change log", 1)
    if len(body) == 1:
        return 0
    section = re.split(r"\n## ", body[1], maxsplit=1)[0]
    return sum(1 for line in section.splitlines() if line.startswith("- "))


