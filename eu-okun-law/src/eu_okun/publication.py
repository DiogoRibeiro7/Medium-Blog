def _balanced(text: str, i: int) -> tuple[str, int]:
    """The content of the brace group opening at text[i], and the index after it."""
    depth, j = 0, i
    while j < len(text):
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        j += 1
        if depth == 0:
            return text[i + 1: j - 1], j
    raise ValueError("Unbalanced braces in the bibliography.")


def parse_bib(text: str) -> list[dict[str, str]]:
    """Entries of a BibTeX file: type, key and brace-delimited fields (any nesting)."""
    entries = []
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        body, _ = _balanced(text, m.end() - len(m.group(0)) + m.group(0).index("{"))
        body = body[body.index(",") + 1:]
        fields: dict[str, str] = {}
        for f in re.finditer(r"(\w+)\s*=\s*\{", body):
            value, _ = _balanced(body, f.end() - 1)
            fields.setdefault(f.group(1).lower(), value)
        entries.append({"type": m.group(1).lower(), "key": m.group(2).strip(), **fields})
    return entries


def _norm(s: str) -> str:
    s = re.sub(r"\\[a-zA-Z]+\s*|[{}\\'\"`^~]", "", s)
    return re.sub(r"[^a-z0-9]", "", s.lower())


def verify_bibliography(bib: Path) -> dict[str, Any]:
    """Resolve every DOI at doi.org (CSL-JSON) and compare titles (needs internet)."""
    from urllib.request import Request, urlopen

    out: dict[str, dict[str, Any]] = {}
    for e in parse_bib(bib.read_text(encoding="utf-8")):
        doi = e.get("doi")
        if not doi:
            entry: dict[str, Any] = {"doi": None, "url": e.get("url"), "isbn": e.get("isbn"),
                                     "note": e.get("note")}
            if e.get("url"):
                try:
                    with urlopen(Request(e["url"], headers={"User-Agent": "Mozilla/5.0"}),
                                 timeout=60) as response:
                        entry["http_status"] = response.status
                        entry["content_type"] = response.headers.get("Content-Type", "")
                except Exception as exc:  # noqa: BLE001 - recorded, and the test fails on it
                    entry["http_status"] = None
                    entry["error"] = str(exc)
            out[e["key"]] = entry
            continue
        request = Request(f"https://doi.org/{doi}", headers={
            "Accept": "application/vnd.citationstyles.csl+json",
            "User-Agent": "Medium-Blog/eu-okun-law bibliography check"})
        try:
            with urlopen(request, timeout=60) as response:
                meta = json.loads(response.read())
            title = meta.get("title", "")
            title = title[0] if isinstance(title, list) else title
            if doi.startswith("10.2908/"):
                # Eurostat dataset DOIs (DataCite) carry multilingual titles: check that the
                # DOI resolves to the dataset code the entry cites instead.
                code = doi.split("/", 1)[1]
                match = code.replace("_", "\\_") in e.get("title", "")
                check = "dataset code"
            else:
                a, b = _norm(title), _norm(e.get("title", ""))
                match = bool(a) and bool(b) and (a.startswith(b[:40]) or b.startswith(a[:40]))
                check = "title"
            out[e["key"]] = {"doi": doi, "resolved": True, "registered_title": title,
                             "checked": check, "title_matches": match}
        except Exception as exc:  # noqa: BLE001 - recorded, and the test fails on it
            out[e["key"]] = {"doi": doi, "resolved": False, "error": str(exc)}
    return dict(sorted(out.items()))


def bibliography_problems(result: Mapping[str, Mapping[str, Any]]) -> list[str]:
    """Entries of a verify_bibliography result that failed their check."""
    problems = []
    for key, r in result.items():
        if r.get("doi"):
            if not r.get("resolved"):
                problems.append(f"{key}: DOI does not resolve")
            elif not r.get("title_matches"):
                problems.append(f"{key}: registered {r.get('checked')} differs")
        elif r.get("url"):
            if r.get("http_status") != 200:
                problems.append(f"{key}: URL returned {r.get('http_status')}")
        elif not (r.get("isbn") or r.get("note")):
            problems.append(f"{key}: no DOI, URL, ISBN or note")
    return problems


