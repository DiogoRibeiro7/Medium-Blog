def _verdict(r: Mapping[str, str]) -> str:
    """'A better', 'B better', or a dash for 'not distinguishable'."""
    if r["verdict"] == f"{r['model_a']} better":
        return "A better"
    if r["verdict"] == f"{r['model_b']} better":
        return "B better"
    return "---"


