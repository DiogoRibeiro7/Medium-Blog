def render_medium(template: str, values: Mapping[str, Value]) -> str:
    missing = sorted({k for k in PLACEHOLDER.findall(template) if k not in values})
    if missing:
        raise KeyError(f"Undefined placeholders: {', '.join(missing)}")
    body = PLACEHOLDER.sub(lambda m: values[m.group(1)].md, template)
    if "$" in body or re.search(r"^\s*\|.*\|\s*$", body, re.M):
        raise ValueError("Medium does not render LaTeX math or Markdown tables.")
    return body


