def values_tex(values: Mapping[str, Value]) -> str:
    lines = ["% Generated by eu-okun publication from the committed results. Do not edit.",
             "\\makeatletter",
             "\\newcommand{\\val}[1]{\\@ifundefined{okun@#1}"
             "{\\PackageError{values}{Undefined value #1}{}}{\\csname okun@#1\\endcsname}}"]
    for key, v in sorted(values.items()):
        lines.append(f"\\expandafter\\def\\csname okun@{key}\\endcsname{{{v.tex}}}")
    lines.append("\\makeatother")
    return "\n".join(lines) + "\n"


def _csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def _tex(x: float, digits: int = 2, signed: bool = True) -> str:
    if not np.isfinite(x):
        return "$-\\infty$" if x < 0 else "$+\\infty$"
    s = f"{x:+.{digits}f}" if signed else f"{x:.{digits}f}"
    return f"${s}$"


def _tex_ci(lo: float, hi: float, digits: int = 2) -> str:
    def one(x: float) -> str:
        if not np.isfinite(x):
            return "-\\infty" if x < 0 else "+\\infty"
        return f"{x:+.{digits}f}"
    return f"$[{one(lo)}, {one(hi)}]$"


