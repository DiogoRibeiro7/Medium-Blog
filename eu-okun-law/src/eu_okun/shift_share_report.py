def _table(header: Sequence[str], rows: Sequence[Sequence[Any]], align: str = "") -> list[str]:
    align = align or "l" + "r" * (len(header) - 1)
    marks = ["---" if a == "l" else "---:" for a in align]
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(marks) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines + [""]


def exposure_rows(inputs: Inputs) -> list[dict[str, Any]]:
    """Per country: value-added shares absorbed by each partner group and at home (%)."""
    rows = []
    for geo in EU27:
        e = inputs.exposure[geo]
        rows.append({
            "geo": geo,
            "p1": 100 * sum(e[p] for p in P1),
            "near": 100 * sum(e[p] for p in NEAR),
            "intra_eu": 100 * sum(e[p] for p in partners_for("P3", geo)),
            "domestic": 100 * e[ISO3[geo]],
            "industry_share": 100 * inputs.balance[geo]["industry_share"],
            "export_share": 100 * inputs.balance[geo]["export_share"],
        })
    return rows


def _years(quarters: float) -> str:
    return f"{quarters:.0f} quarters ({quarters / 4:.0f} years)"


def render(review: ShiftShareReview, assets: str, command: str) -> str:
    """Assemble the Markdown report."""
    p1 = review.results["P1"]
    c = p1.central
    go = review.decision == "go"
    lines = [
        "# Shift-share foreign-demand instrument: feasibility", "",
        "Generated by `eu-okun shift-share` from the frozen OECD snapshot (TiVA 2025 value "
        "added in final demand; quarterly national accounts) and the frozen Eurostat "
        "quarterly snapshot. Design, calibration and the go/no-go rule were pre-registered in "
        "[SHIFT_SHARE_PROTOCOL.md](../SHIFT_SHARE_PROTOCOL.md) before any number was "
        "computed. No unemployment series is used; the only domestic quantity is the "
        "residual standard deviation of GDP growth.", "",
        "`Z[i,t] = sum_p e[i,p] g[p,t]`: `e[i,p]` is the share of country i's value added "
        "absorbed in partner p's final demand (2005-2007), `g[p,t]` partner p's quarterly "
        "real GDP growth. `Z` is the predicted contribution of foreign demand to i's GDP "
        "growth (pp).", "",
        "## Decision", "",
        f"**{'Go' if go else 'No go'}.** For P1 (distant demand, the only set whose exclusion "
        f"restriction the protocol judges defensible), the benchmark expected first-stage t "
        f"at the central calibration is **{c.expected_t:.2f}**, against the registered "
        f"threshold {WEAK_T} (F = 10). The probability that a 90% Anderson-Rubin set would "
        f"be bounded is about {100 * c.p_bounded:.0f}%.", "",
    ]
    if not go:
        lines += [
            f"- Reaching |t| = {WEAK_T} would need a pass-through of {p1.beta_needed:.1f} pp of "
            f"GDP growth per pp of predicted foreign demand (central: 1, by construction of "
            f"value-added shares), or about {_years(p1.quarters_needed)} at the central "
            f"calibration instead of the {p1.quarters} usable quarters.",
            "- Under the protocol, no shift-share IV is estimated. Country-specific GDP "
            "shocks remain unidentified in this study.", ""]
    # 1. Exposure
    rows = exposure_rows(review.inputs)
    lines += ["## 1. Exposure", "",
              "Share of each country's value added absorbed in final demand abroad and at home, "
              "2005-2007 averages (%). Near extra-EU is GBR, CHE, NOR and TUR (P2 adds them to "
              "P1). Alphabetical.", ""]
    lines += _table(["Country", "P1 distant", "Near extra-EU", "Intra-EU (other 26)",
                     "Domestic", "Industry (B-E) share of VA", "Gross exports / VA"],
                    [[r["geo"], f"{r['p1']:.1f}", f"{r['near']:.1f}", f"{r['intra_eu']:.1f}",
                      f"{r['domestic']:.1f}", f"{r['industry_share']:.1f}",
                      f"{r['export_share']:.1f}"] for r in rows])
    p1_values = [r["p1"] for r in rows]
    lines += [f"P1 exposure ranges from {min(p1_values):.1f}% to {max(p1_values):.1f}% of value "
              f"added (cross-country standard deviation {np.std(p1_values, ddof=1):.1f} pp). "
              f"Balance: its correlation across the 27 countries is "
              f"{review.balance['industry_share']:+.2f} with the industry share and "
              f"{review.balance['export_share']:+.2f} with gross exports / value added. "
              + ("Exposure is correlated with economic structure, so exclusion needs shocks "
                 "specific to industry or to open economies to be absent or absorbed by the "
                 "quarter effects."
                 if max(abs(v) for v in review.balance.values()) >= 0.3 else
                 "Exposure is only weakly correlated with these characteristics."), "",
              f"![Exposure by country]({assets}/exposure.png)", ""]

    # 2. Power
    lines += ["## 2. Identifying variation and benchmark power", "",
              "`Z~` is `Z` after country effects, quarter effects and four lags of `Z`; "
              "`S = sum Z~^2`. Benchmark expected first-stage t = `beta sqrt(S) / sigma_u` with "
              "independent, homoskedastic errors; `sigma_u` is the residual standard deviation "
              "of quarterly GDP growth after country and quarter effects and four lags of GDP "
              f"growth, the unemployment change and the participation change ({review.sigma_n} "
              f"country-quarters, origins {FIRST_ORIGIN} to {LAST_ORIGIN} without windows "
              "touching 2020-2021). P(bounded) approximates the probability that a 90% "
              "Anderson-Rubin set is bounded.", ""]
    table = []
    for key, res in review.results.items():
        table.append([SET_LABELS[key], str(res.n), str(res.quarters),
                      f"{res.instrument_sd:.4f}", f"{res.sigma_u:.3f}",
                      f"{res.central.expected_t:.2f}", f"{100 * res.central.p_bounded:.0f}%",
                      f"{res.beta_needed:.1f}", f"{res.quarters_needed:.0f}"])
    lines += _table(["Partner set", "Country-quarters", "Quarters", "sd of Z~ (pp)", "sigma_u (pp)",
                     "Expected t (central)", "P(bounded)", "beta needed for t = 3.16",
                     "Quarters needed at beta = 1"], table, "lrrrrrrrr")
    lines += ["Calibrations for P1:", ""]
    lines += _table(["Calibration", "beta", "sigma_u (pp)", "Expected t", "P(bounded)"],
                    [[cal.label, f"{cal.beta:g}", f"{cal.sigma:.3f}", f"{cal.expected_t:.2f}",
                      f"{100 * cal.p_bounded:.0f}%"] for cal in p1.calibrations], "lrrrr")
    best = max(p1.calibrations, key=lambda cal: cal.expected_t)
    lines += [f"Even the most favourable P1 calibration ({best.label}) gives an expected t of "
              f"{best.expected_t:.2f}. The benchmark ignores the cross-country correlation of "
              "errors within a quarter, which quarter-clustered inference would have to "
              "respect.", ""]
    p2, p3 = review.results["P2"], review.results["P3"]
    lines += [f"Adding the near extra-EU partners (P2) changes the central expected t to "
              f"{p2.central.expected_t:.2f}; the intra-EU leave-one-out instrument (P3) gives "
              f"{p3.central.expected_t:.2f}. "
              + ("Relevance rises only with partners whose exclusion restriction the protocol "
                 "judges not defensible (section 3)."
                 if max(p2.central.expected_t, p3.central.expected_t) > c.expected_t else
                 "Neither comparison set is stronger than P1."), ""]

    # 3. Weights
    lines += ["## 3. Where the variation comes from", "",
              "Rotemberg-type weights: each partner's share of `S` "
              "(`(M Z_p)'(M Z) / S`, summing to one; negative weights are possible) and each "
              "country's share of `S`. Alphabetical.", ""]
    lines += _table(["Partner", "P1 weight"],
                    [[p, f"{p1.partner_weights[p]:+.3f}"] for p in sorted(p1.partner_weights)])
    lines += _table(["Country", "Share of S (P1)"],
                    [[g, f"{p1.country_weights.get(g, 0.0):.3f}"] for g in EU27])
    top_p = max(p1.partner_weights, key=lambda k: p1.partner_weights[k])
    top_c = max(p1.country_weights, key=lambda k: p1.country_weights[k])
    lines += [f"The largest partner weight is {top_p} ({p1.partner_weights[top_p]:+.2f}) and "
              f"the largest country share {top_c} ({p1.country_weights[top_c]:.2f}).", ""]

    # 4. Meaning
    lines += [
        "## 4. What this means", "",
        "- The defensible instrument moves predicted GDP growth by "
        f"{p1.instrument_sd:.4f} pp (standard deviation after effects and lags), against "
        f"residual GDP growth noise of {p1.sigma_u:.3f} pp: distant foreign demand differs "
        "too little across EU countries, net of the common EU cycle, to identify "
        "country-specific GDP shocks." if not go else
        "- The defensible instrument is strong enough at the benchmark; estimation requires "
        "a further protocol.",
        "- *Under which assumptions are country-specific GDP shocks identifiable?* With an "
        "exogenous, strong, country-specific shifter. The distant-demand shift-share is the "
        "most defensible public candidate"
        + (", and it is not strong enough in this sample." if not go else
           "; whether it identifies them is for the estimation protocol."),
        "- Nothing here is a causal estimate, and no outcome was examined.", "",
        "## 5. Provenance and reproduction", "",
    ]
    prov = review.provenance
    if prov:
        files = "; ".join(f"`{name}` `{v['sha256'][:16]}...`"
                          for name, v in prov["oecd_files"].items())
        lines += [f"OECD snapshot downloaded {prov['oecd_downloaded_at_utc']}: {files} "
                  f"(full hashes and URLs in `provenance.json`; OECD data, CC BY 4.0). Eurostat "
                  f"snapshot manifest SHA-256 `{prov['eurostat_manifest_sha256']}`.", ""]
    lines += ["```bash", "poetry install --extras \"bayes report\"", command, "```", ""]
    return "\n".join(lines)


