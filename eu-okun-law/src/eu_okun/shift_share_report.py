def write_figure(review: ShiftShareReview, directory: Path, source: str) -> None:
    """Exposure by country: distant, near extra-EU and intra-EU shares of value added."""
    from eu_okun.review_figures import AQUA, BLUE, INK2, ORANGE, _finish, _pyplot

    plt = _pyplot()
    rows = exposure_rows(review.inputs)
    fig, axes = plt.subplots(1, 3, figsize=(11.0, 7.6), sharey=True)
    ys = np.arange(len(rows))[::-1]
    for ax, (key, label, colour) in zip(axes, (
            ("p1", "P1 distant demand", BLUE), ("near", "Near extra-EU (GBR, CHE, NOR, TUR)",
                                                ORANGE),
            ("intra_eu", "Intra-EU (other 26)", AQUA)), strict=True):
        ax.barh(ys, [r[key] for r in rows], color=colour, height=0.7)
        ax.set_title(label, fontsize=9.5)
        ax.set_xlabel("% of value added, 2005-2007")
        ax.grid(axis="y", visible=False)
    axes[0].set_yticks(ys)
    axes[0].set_yticklabels([r["geo"] for r in rows], fontsize=8)
    axes[0].tick_params(axis="y", length=0)
    fig.suptitle("Value added absorbed in final demand abroad (OECD TiVA 2025)", x=0.01,
                 ha="left", fontsize=10.5, fontweight="bold", color=INK2)
    fig.subplots_adjust(wspace=0.15, top=0.9, bottom=0.1)
    _finish(plt, fig, directory / "exposure.png", source, credit_y=0.0)


def write_tables(review: ShiftShareReview, directory: Path) -> None:
    """Feasibility, calibrations, weights, exposure, balance and provenance."""
    directory.mkdir(parents=True, exist_ok=True)

    def write(name: str, rows: Sequence[Mapping[str, Any]]) -> None:
        with (directory / name).open("w", encoding="utf-8", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator="\n")
            writer.writeheader()
            writer.writerows(rows)

    write("feasibility.csv", [{"set": k, "n": r.n, "quarters": r.quarters, "s": r.s,
                               "instrument_sd": r.instrument_sd, "sigma_u": r.sigma_u,
                               "expected_t": r.central.expected_t,
                               "p_bounded": r.central.p_bounded,
                               "beta_needed": r.beta_needed,
                               "quarters_needed": r.quarters_needed,
                               "decision": review.decision if k == "P1" else ""}
                              for k, r in review.results.items()])
    write("calibrations.csv", [{"set": k, **asdict(cal)} for k, r in review.results.items()
                               for cal in r.calibrations])
    write("partner_weights.csv", [{"set": k, "partner": p, "weight": w}
                                  for k, r in review.results.items()
                                  for p, w in r.partner_weights.items()])
    write("country_weights.csv", [{"set": k, "geo": g, "share": w}
                                  for k, r in review.results.items()
                                  for g, w in r.country_weights.items()])
    write("exposure_summary.csv", exposure_rows(review.inputs))
    write("balance.csv", [{"set": "P1", "covariate": k, "correlation": v}
                          for k, v in review.balance.items()])
    (directory / "provenance.json").write_text(json.dumps(review.provenance, indent=1) + "\n",
                                               encoding="utf-8", newline="\n")


def write_report(snapshot: Path, eurostat_dir: Path, output_dir: Path,
                 report: Path | None = None, figures: bool = True) -> ShiftShareReview:
    """Build the review and write tables, figure and the Markdown report."""
    review = build_review(snapshot, eurostat_dir)
    report = report or output_dir / "SHIFT_SHARE_FEASIBILITY.md"
    write_tables(review, output_dir)
    if figures:
        write_figure(review, output_dir, "Source: OECD TiVA 2025 edition (CC BY 4.0). "
                     "Shares of value added absorbed in each area's final demand.")
    assets = Path(os.path.relpath(output_dir, report.parent)).as_posix()
    command = (f"poetry run eu-okun shift-share --data-dir {snapshot.as_posix()} "
               f"--eurostat-dir {eurostat_dir.as_posix()} --output-dir {output_dir.as_posix()} "
               f"--report {report.as_posix()}")
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(render(review, assets, command), encoding="utf-8", newline="\n")
    return review
