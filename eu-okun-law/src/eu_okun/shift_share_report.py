"""Tables, figure and Markdown report of the shift-share feasibility study.

Runs the computation registered in ``SHIFT_SHARE_PROTOCOL.md`` on the frozen OECD
snapshot and the frozen Eurostat quarterly snapshot, and writes
``SHIFT_SHARE_FEASIBILITY.md``. Every number and the go/no-go decision are computed here.
"""

from __future__ import annotations

import csv
import json
import os
from collections.abc import Mapping, Sequence
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from eu_okun.audit import audit_snapshot
from eu_okun.baseline import _read_panel
from eu_okun.contract import EU27, quarter_sequence
from eu_okun.shift_share import (
    FIRST_ORIGIN,
    ISO3,
    LAST_ORIGIN,
    NEAR,
    P1,
    PARTNER_SETS,
    SET_LABELS,
    SHIFT_START,
    WEAK_T,
    Feasibility,
    Inputs,
    audit_shift_share,
    balance,
    decision,
    feasibility,
    instrument,
    load_inputs,
    partners_for,
    sigma_u,
)


@dataclass
class ShiftShareReview:
    """Everything the report is generated from."""

    inputs: Inputs
    results: dict[str, Feasibility]
    sigma_n: int
    balance: dict[str, float]
    decision: str
    provenance: dict[str, Any] = field(default_factory=dict)


def review_from_inputs(inputs: Inputs, eurostat: Mapping[tuple[str, str], Mapping[str, Any]],
                       provenance: dict[str, Any] | None = None) -> ShiftShareReview:
    """Every registered computation on prepared inputs."""
    quarters = quarter_sequence(SHIFT_START, LAST_ORIGIN)
    sigma, n_sigma = sigma_u(eurostat, quarters)
    results = {key: feasibility(instrument(inputs, key), sigma, key) for key in PARTNER_SETS}
    return ShiftShareReview(inputs, results, n_sigma, balance(inputs, "P1"),
                            decision(results), provenance or {})


def build_review(snapshot: Path, eurostat_dir: Path) -> ShiftShareReview:
    """Audit both snapshots and run the registered computation."""
    manifest = audit_shift_share(snapshot)
    audit = audit_snapshot(eurostat_dir)
    panel = _read_panel(eurostat_dir / "processed" / "eu27_quarterly.csv")
    growth: dict[str, dict[str, float]] = {}
    for (geo, quarter), row in panel.items():
        if row.get("gdp") is not None:
            growth.setdefault(geo, {})[quarter] = float(row["gdp"])  # type: ignore[arg-type]
    provenance = {
        "oecd_files": {f["file"]: {"sha256": f["sha256"], "url": f["url"],
                                   "licence": f["licence"]} for f in manifest["files"]},
        "oecd_downloaded_at_utc": manifest["downloaded_at_utc"],
        "eurostat_manifest_sha256": audit["snapshot_manifest_sha256"],
    }
    return review_from_inputs(load_inputs(snapshot, growth), panel, provenance)


