"""The core robustness grid without the participation control (``CORE_GRID_PROTOCOL.md``).

The classical review's verdict rule (``review.verdict_for``) applied to the 12
participation-free estimates of its core grid, read from the committed
``docs/review/grid.csv``. The published 24-estimate verdicts are reproduced first.
"""

from __future__ import annotations

import csv
import json
from collections.abc import Sequence
from dataclasses import asdict, dataclass
from pathlib import Path

from eu_okun.contract import EU27
from eu_okun.review import CORE_LAGS, CORE_SAMPLES, VERDICTS, GridRow, verdict_for


def read_grid(path: Path) -> dict[tuple[str, str, int, bool], GridRow]:
    with path.open(encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    out = {}
    for r in rows:
        row = GridRow(r["sample"], r["geo"], int(r["gdp_lags"]), r["participation"] == "True",
                      int(r["n"]), r["first"], r["last"], float(r["gdp_sum"]), float(r["se"]),
                      float(r["ci_low"]), float(r["ci_high"]), float(r["r_squared"]))
        out[(row.sample, row.geo, row.gdp_lags, row.participation)] = row
    return out


def core(lookup: dict[tuple[str, str, int, bool], GridRow], geo: str,
         participation: Sequence[bool]) -> list[GridRow]:
    return [lookup[(s, geo, k, p)] for s in CORE_SAMPLES for k in CORE_LAGS
            for p in participation]


@dataclass(frozen=True)
class CountryVerdict:
    geo: str
    published: str                      # 24 estimates, as in docs/review/robustness.csv
    published_without_pandemic: str
    verdict: str                        # 12 participation-free estimates
    verdict_without_pandemic: str       # 9: without the full sample
    estimates: int
    negative: int
    below_zero: int

    @property
    def changed(self) -> bool:
        return self.verdict != self.published


def reclassify(grid_csv: Path, robustness_csv: Path) -> list[CountryVerdict]:
    lookup = read_grid(grid_csv)
    with robustness_csv.open(encoding="utf-8") as stream:
        published = {r["geo"]: r for r in csv.DictReader(stream)}
    out = []
    for geo in EU27:
        full = core(lookup, geo, (False, True))
        old, old_wo = verdict_for(full), verdict_for([r for r in full if r.sample != "full"])
        if (old, old_wo) != (published[geo]["verdict"],
                             published[geo]["verdict_without_pandemic"]):
            raise ValueError(f"{geo}: the published verdicts are not reproduced (protocol, "
                             "section 2); the run stops.")
        free = core(lookup, geo, (False,))
        out.append(CountryVerdict(
            geo, old, old_wo, verdict_for(free),
            verdict_for([r for r in free if r.sample != "full"]), len(free),
            sum(r.gdp_sum < 0 for r in free), sum(r.ci_high < 0 for r in free)))
    return out


def summary(rows: Sequence[CountryVerdict]) -> dict[str, object]:
    def count(field: str, value: str) -> int:
        return sum(getattr(r, field) == value for r in rows)

    return {
        "robust_published": count("published", "robust_negative"),
        "robust": count("verdict", "robust_negative"),
        "precision_dependent": count("verdict", "negative_precision_dependent"),
        "sign_unstable": count("verdict", "sign_unstable"),
        "robust_without_pandemic_published": count("published_without_pandemic",
                                                   "robust_negative"),
        "robust_without_pandemic": count("verdict_without_pandemic", "robust_negative"),
        "changed": {r.geo: [r.published, r.verdict] for r in rows if r.changed},
    }


def render(rows: Sequence[CountryVerdict], command: str) -> str:
    s = summary(rows)
    label = {k: v.lower() for k, v in VERDICTS.items()}
    changed = s["changed"]
    assert isinstance(changed, dict)
    lines = [
        "# The core robustness grid without the participation control", "",
        "Generated by `eu-okun core-grid` under "
        "[CORE_GRID_PROTOCOL.md](../CORE_GRID_PROTOCOL.md), registered before the "
        "re-classification was computed. The classical review's verdict rule applied to the "
        "12 participation-free estimates of its core grid (four samples × lags 1, 2 and 4); "
        "the published verdicts use all 24, half with the participation control. The "
        "published verdicts are reproduced first.", "",
        "## Summary", "",
        f"- **Robust negative:** {s['robust']} countries without the participation control, "
        f"against {s['robust_published']} published.",
        f"- **Negative, significance specification-dependent:** {s['precision_dependent']}; "
        f"**sign-unstable:** {s['sign_unstable']}.",
        f"- **Without the full sample:** {s['robust_without_pandemic']} robust negative, "
        f"against {s['robust_without_pandemic_published']} published.",
        "- **Changed:** " + ("; ".join(f"{g} ({label[a]} to {label[b]})"
                                       for g, (a, b) in changed.items()) or "none") + ".",
        "", "## Countries", "",
        "| Country | Published (24) | Without participation (12) | Without the full sample "
        "(9) | Negative estimates | Intervals below zero |",
        "| --- | --- | --- | --- | ---: | ---: |",
    ]
    for r in rows:
        mark = f"**{r.geo}**" if r.changed else r.geo
        lines.append(f"| {mark} | {label[r.published]} | {label[r.verdict]} | "
                     f"{label[r.verdict_without_pandemic]} | {r.negative} of {r.estimates} | "
                     f"{r.below_zero} of {r.estimates} |")
    lines += ["", "## Reproduction", "", "```bash", command, "```", ""]
    return "\n".join(lines)


def write_report(grid_csv: Path, robustness_csv: Path, output_dir: Path,
                 report: Path | None = None) -> list[CountryVerdict]:
    rows = reclassify(grid_csv, robustness_csv)
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "verdicts.csv").open("w", encoding="utf-8", newline="\n") as stream:
        writer = csv.DictWriter(stream, fieldnames=[*asdict(rows[0]), "changed"],
                                lineterminator="\n")
        writer.writeheader()
        writer.writerows({**asdict(r), "changed": r.changed} for r in rows)
    (output_dir / "summary.json").write_text(json.dumps(summary(rows), indent=1) + "\n",
                                             encoding="utf-8", newline="\n")
    if report is not None:
        command = (f"eu-okun core-grid --grid {grid_csv.as_posix()} --robustness "
                   f"{robustness_csv.as_posix()} --output-dir {output_dir.as_posix()} "
                   f"--report {report.as_posix()}")
        report.write_text(render(rows, command), encoding="utf-8", newline="\n")
    return rows
