"""Create a short executable walkthrough using the canonical study functions."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent


def markdown(source: str, identifier: str) -> dict[str, Any]:
    """Build one Markdown cell with a stable notebook cell identifier."""

    return {"cell_type": "markdown", "id": identifier, "metadata": {},
            "source": source.splitlines(keepends=True)}


def code(source: str, identifier: str) -> dict[str, Any]:
    """Build an unexecuted Python cell with the Jupyter v4 required fields."""

    return {"cell_type": "code", "id": identifier, "metadata": {},
            "source": source.splitlines(keepends=True),
            "execution_count": None, "outputs": []}


def notebook() -> dict[str, Any]:
    """Describe all nine independent experiments and ten rendered figures."""

    cells = [
        markdown(
            "# A Cluster Is Not a Population\n\n"
            "Article #28 companion. Nine seeded synthetic studies, ten figures, "
            "and eighteen CSV evidence tables. These are conditional comparisons, "
            "not estimates of natural or causal population types.\n",
            "introduction",
        ),
        markdown(
            "## What the algorithms optimize\n\n"
            "- **K-means:** minimizes within-cluster squared Euclidean distance.\n"
            "- **DBSCAN:** groups points connected by sufficiently dense neighborhoods.\n"
            "- **Gaussian mixtures:** maximize a likelihood under distributional "
            "and covariance assumptions; BIC penalizes model dimension.\n"
            "- **Silhouette/ARI/stability:** evaluate different targets, none of "
            "which automatically identifies scientific populations.\n",
            "models",
        ),
        code(
            "from pathlib import Path\n"
            "import tempfile\n"
            "import numpy as np\n"
            "from IPython.display import Image, display\n"
            "from analysis import Design, EXPERIMENTS, FIGURES, run\n"
            "print('Experiments:', ', '.join(EXPERIMENTS))\n"
            "print('Independent quick-run seed:', Design().seed)\n",
            "imports",
        ),
        markdown(
            "## Reproduce without overwriting canonical evidence\n\n"
            "The quick design uses three independent outer replications for "
            "every scenario. A temporary output directory isolates its "
            "figures and CSVs. Full canonical evidence is regenerated by "
            "running the script without the quick flag.\n",
            "setup",
        ),
        code(
            "with tempfile.TemporaryDirectory() as directory:\n"
            "    path = Path(directory)\n"
            "    summary = run(Design(root=path, quick=True))\n"
            "    print('Tables:', len(list((path / 'results').glob('*.csv'))))\n"
            "    print('Figures:', len(list((path / 'figures').glob('*.png'))))\n"
            "    for figure in FIGURES:\n"
            "        display(Image(filename=str(path / 'figures' / f'{figure}_quick.png')))\n",
            "execute",
        ),
        markdown(
            "## Interpretation\n\n"
            "The generator labels supply an **oracle** that is unavailable "
            "in ordinary clustering tasks. A good ARI to those labels is "
            "not an external causal validation; poor ARI can also reflect "
            "an unsuitable target. Bootstrap stability is measured on "
            "the same untouched anchor points. Read the article and "
            "README for assumptions, derivations, and limitations.\n",
            "limits",
        ),
    ]
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python",
                           "name": "python3"},
            "language_info": {"name": "python", "version": "3.12"},
        },
        "nbformat": 4, "nbformat_minor": 5,
    }


def main() -> None:
    """Write a deterministic, valid notebook beside the article source."""

    target = ROOT / "clustering_is_not_a_population.ipynb"
    target.write_text(
        json.dumps(notebook(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(target.name)


if __name__ == "__main__":
    main()
