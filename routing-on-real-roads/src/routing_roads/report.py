"""docs/DATA.md, generated from the derived tables alone. No route is solved."""

from __future__ import annotations

import csv
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
from numpy.typing import NDArray

from routing_roads.contract import PAIRS, Pair

IntArray = NDArray[np.int64]


@dataclass(frozen=True)
class Derived:
    points: list[dict[str, str]]
    road: dict[str, IntArray]
    straight: dict[str, IntArray]
    days: list[dict[str, str]]
    manifest: dict[str, Any]


def load(directory: Path) -> Derived:
    with (directory / "points.csv").open(encoding="utf-8") as stream:
        points = list(csv.DictReader(stream))
    with (directory / "days.csv").open(encoding="utf-8") as stream:
        days = list(csv.DictReader(stream))
    road = {p.key: np.loadtxt(directory / f"{p.key}_road.csv", delimiter=",", dtype=np.int64,
                              ndmin=2) for p in PAIRS}
    straight = {p.key: np.loadtxt(directory / f"{p.key}_straight.csv", delimiter=",",
                                  dtype=np.int64, ndmin=2) for p in PAIRS}
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    return Derived(points, road, straight, days, manifest)


def area_indices(d: Derived, pair: Pair, with_other: bool) -> list[int]:
    """Point indices of an area: the depot (0) and its pharmacies (section 4)."""
    rows = [p for p in d.points if p["pair"] == pair.key]
    keep = (pair.city, pair.other) if with_other else (pair.city,)
    return [0] + [int(p["index"]) for p in rows
                  if p["role"] == "pharmacy" and p["municipality"] in keep]


def pair_ratios(road: IntArray, straight: IntArray, idx: list[int]) -> NDArray[np.float64]:
    """Road over straight-line distance for ordered pairs of distinct pharmacies (the
    depot, ``idx[0]``, left out) with a positive straight-line distance."""
    pharm = np.array(idx[1:])
    r, s = road[np.ix_(pharm, pharm)], straight[np.ix_(pharm, pharm)]
    positive = ~np.eye(pharm.size, dtype=bool) & (s > 0)
    return np.asarray(r[positive] / s[positive], dtype=np.float64)


def matrix_summary(road: IntArray, straight: IntArray, idx: list[int]) -> dict[str, Any]:
    """Over ordered pairs of distinct pharmacies (the depot left out): the ratio of road to
    straight-line distance, and the asymmetry of the road distance."""
    pharm = np.array(idx[1:])
    r, s = road[np.ix_(pharm, pharm)], straight[np.ix_(pharm, pharm)]
    off = ~np.eye(pharm.size, dtype=bool)
    ratio = pair_ratios(road, straight, idx)
    upper = np.triu(np.ones_like(r, dtype=bool), 1)
    a, b = r[upper], r.T[upper]
    mean = (a + b) / 2
    asym = np.abs(a - b)[mean > 0] / mean[mean > 0]
    return {"pharmacies": int(pharm.size), "same_node_pairs": int(np.sum(off & (s == 0))),
            "ratio": {f"p{q}": float(np.percentile(ratio, q)) for q in (5, 25, 50, 75, 95)},
            "asymmetry": {"p50": float(np.percentile(asym, 50)),
                          "p90": float(np.percentile(asym, 90))}}


def orders(d: Derived, pair: Pair, idx: list[int]) -> dict[str, float]:
    keep = set(idx)
    per_day = [sum(1 for r in d.days if r["pair"] == pair.key and int(r["day"]) == day
                   and int(r["index"]) in keep) for day in range(1, d.manifest["days"] + 1)]
    return {"mean": float(np.mean(per_day)), "min": min(per_day), "max": max(per_day)}


def render(d: Derived, command: str) -> str:
    m = d.manifest
    e = m["extract"]
    lines = [
        "# Data: road networks, pharmacies and distances", "",
        "Generated by `routing-roads data` from the pinned extract, as section 4 of "
        "[METHODS.md](../METHODS.md) fixes it. **No route has been solved.** Map data © "
        "OpenStreetMap contributors, under the Open Database Licence; the tables in "
        "`data/derived/` are a derived database under the same licence.", "",
        f"- **Extract:** `{e['file']}`, {e['bytes']:,} bytes, MD5 `{e['md5']}`, SHA-256 "
        f"`{e['sha256']}`, checked before every build.",
        "- **Versions:** " + ", ".join(f"{k} {v}" for k, v in m["versions"].items()) + ".",
        f"- **Network:** OSMnx's `drive` ways with a node in the area's bounding box, clipped "
        f"to the area buffered by {m['buffer_m'] / 1000:.0f} km (in {m['projected_crs']}), "
        "simplified, largest strongly connected component.",
        f"- **Days:** {m['days']} per pair, seed {m['days_seed']}.", "",
        "## Networks and points", "",
        "| Pair | Drivable ways read | Nodes clipped | Nodes kept (strongly connected) "
        "| Edges kept | Pharmacies | Snap distance, median / max (m) "
        "| Pharmacies sharing a node | Depot snap (m) | Depot variant snap (m) |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for pair in PAIRS:
        p = m["pairs"][pair.key]
        rows = [r for r in d.points if r["pair"] == pair.key]
        pharm = [r for r in rows if r["role"] == "pharmacy"]
        snaps = [float(r["snap_m"]) for r in pharm]
        nodes = [r["node"] for r in pharm]
        shared = sum(1 for n in nodes if nodes.count(n) > 1)
        depot = next(r for r in rows if r["role"] == "depot")
        variant = next(r for r in rows if r["role"] == "depot_variant")
        lines.append(
            f"| {pair.city} with {pair.other} | {p['drivable_ways']:,} | {p['nodes_clipped']:,} | "
            f"{p['nodes']:,} | {p['edges']:,} | {len(pharm)} | {np.median(snaps):.0f} / "
            f"{max(snaps):.0f} | {shared} | {float(depot['snap_m']):.0f} | "
            f"{float(variant['snap_m']):.0f} |")
    lines += ["", "## Distances by area (descriptive)", "",
              "Over ordered pairs of distinct pharmacies, the depot left out. The median ratio "
              "of road to straight-line distance is E4's circuity factor α. Pairs whose "
              "pharmacies snap to the same node have no ratio and are counted apart.", "",
              "| Area | Pharmacies | Orders a day, mean (min-max) | Road / straight, 5th | 25th "
              "| median (α) | 75th | 95th | Same-node pairs | Asymmetry, median / 90th |",
              "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for pair in PAIRS:
        for with_other in (False, True):
            idx = area_indices(d, pair, with_other)
            s = matrix_summary(d.road[pair.key], d.straight[pair.key], idx)
            o = orders(d, pair, idx)
            name = f"{pair.city} with {pair.other}" if with_other else pair.city
            q = s["ratio"]
            lines.append(
                f"| {name} | {s['pharmacies']} | {o['mean']:.1f} ({o['min']}-{o['max']}) | "
                f"{q['p5']:.2f} | {q['p25']:.2f} | {q['p50']:.2f} | {q['p75']:.2f} | "
                f"{q['p95']:.2f} | {s['same_node_pairs']} | {s['asymmetry']['p50']:.1%} / "
                f"{s['asymmetry']['p90']:.1%} |")
    lines += ["", "## Where the shortest road paths cross the water", "",
              "For every ordered pair of points on opposite banks (each point's bank is its "
              "municipality), the edge where the shortest road path between them crosses: an "
              "edge whose two ends lie in the pair's two municipalities, which meet only in "
              "the river. Each crossing's share of those paths; crossings on under 1% of "
              "paths are left out.", ""]
    for pair in PAIRS:
        c = m["pairs"][pair.key]["crossings"]
        used = [(n, v) for n, v in c["bridges"].items() if v >= 0.01]
        lines.append(f"- **{pair.city} and {pair.other}** ({c['paths']:,} paths): "
                     + "; ".join(f"{n} {v:.0%}" for n, v in used) + ".")
    lines += ["", "## Reproduce", "", "```", command, "```", ""]
    return "\n".join(lines)
