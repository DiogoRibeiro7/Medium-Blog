"""Audit OWID and WDI source snapshots before any empirical regression.

The program never invents country-level values. It checks source-file SHA-256
against the manifest produced by source_pipeline.py, verifies compatible
country codes, and inventories the coverage by source and observation year.

No Forbes data or causal estimands are generated by this preflight.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any, Mapping

import pandas as pd

from source_pipeline import (
    SOURCE_URLS,
    read_owid_poverty,
    read_wdi_indicator,
)


class SourceValidationError(ValueError):
    """Raised when an archived source is absent, altered, or inconsistent."""


def sha256_file(path: Path) -> str:
    """Hash the exact input bytes for provenance, not re-serialized content."""
    if not isinstance(path, Path) or not path.is_file():
        raise SourceValidationError(f"Missing source file: {path}")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(snapshot_dir: Path) -> dict[str, dict[str, Any]]:
    """Check the manifest and every expected local source against its SHA.

    Only three public OWID/WDI files are allowed to satisfy this check.
    These are not individual billionaire records.
    """
    if not isinstance(snapshot_dir, Path):
        raise TypeError("snapshot_dir must be a pathlib.Path")
    manifest_path = snapshot_dir / "SOURCE_MANIFEST.json"
    if not manifest_path.is_file():
        raise SourceValidationError("SOURCE_MANIFEST.json not found")
    manifest: Any = json.loads(manifest_path.read_text(encoding="utf-8"))
    if not isinstance(manifest, dict) or not isinstance(manifest.get("files"), dict):
        raise SourceValidationError("Malformed source manifest")
    records: dict[str, dict[str, Any]] = manifest["files"]
    if set(records) != set(SOURCE_URLS):
        raise SourceValidationError("Manifest must contain exactly the three public sources")
    for filename, url in SOURCE_URLS.items():
        record = records[filename]
        if not isinstance(record, dict):
            raise SourceValidationError(f"Manifest record is malformed: {filename}")
        if record.get("source_url") != url:
            raise SourceValidationError(f"Source URL mismatch: {filename}")
        path = snapshot_dir / filename
        checksum = sha256_file(path)
        if record.get("sha256") != checksum:
            raise SourceValidationError(f"SHA-256 checksum mismatch: {filename}")
        if not isinstance(record.get("bytes"), int) or record["bytes"] != path.stat().st_size:
            raise SourceValidationError(f"Byte-size mismatch: {filename}")
        if path.stat().st_size < 100:
            raise SourceValidationError(f"Unexpectedly short source file: {filename}")
    return records


def summarize_public_sources(
    snapshot_dir: Path, *, minimum_overlap: int = 60
) -> dict[str, Any]:
    """Summarize compatible OWID/WDI countries and distinct observation years.

    Args:
        snapshot_dir: Directory with the exact downloaded snapshot files
            and SHA-256 manifest.
        minimum_overlap: Minimum common ISO3 records to detect truncated
            responses. Override in synthetic tests only; for real captures
            this remains 60, rather than falsely suggesting complete coverage.

    Returns:
        JSON-serializable source coverage report; it is not a regression.

    Raises:
        SourceValidationError: If the source contract is violated, there
            are too few matched countries, or basic coverage checks fail.
    """
    if not isinstance(minimum_overlap, int) or minimum_overlap < 1:
        raise ValueError("minimum_overlap must be an integer >= 1")
    records = verify_manifest(snapshot_dir)
    poverty = read_owid_poverty(snapshot_dir / "owid_30usd_2021_ppp.csv")
    gdp = read_wdi_indicator(
        snapshot_dir / "wdi_gdp_ppp_constant.json",
        indicator="NY.GDP.PCAP.PP.KD",
        field="gdp_ppp_per_capita",
    )
    population = read_wdi_indicator(
        snapshot_dir / "wdi_population.json",
        indicator="SP.POP.TOTL",
        field="population",
    )
    # One-to-one joins prevent silent country duplication; neither WDI
    # aggregates nor unmatched source rows enter a future regression.
    joined = poverty.merge(gdp, on="iso3", how="inner", validate="one_to_one")
    joined = joined.merge(population, on="iso3", how="inner", validate="one_to_one")
    if len(joined) < minimum_overlap:
        raise SourceValidationError(
            f"Only {len(joined)} common country codes; expected at least {minimum_overlap}"
        )
    years: dict[str, dict[str, int]] = {}
    for field in ("poverty_year", "gdp_ppp_per_capita_year", "population_year"):
        series = pd.to_numeric(joined[field], errors="raise")
        years[field] = {"min": int(series.min()), "max": int(series.max())}
    return {
        "report_kind": "descriptive public-source coverage; not empirical regression",
        "poverty_unit": "percentage of people under $30/day, 2021 PPP",
        "owid_year_semantics": (
            "OWID indicator observation year; not necessarily PIP household survey year"
        ),
        "source_files": {
            filename: {
                "source_url": row["source_url"],
                "sha256": row["sha256"],
                "bytes": row["bytes"],
            }
            for filename, row in sorted(records.items())
        },
        "n_owid_countries_in_2020_to_2025_window": int(len(poverty)),
        "n_wdi_gdp_countries_in_2020_to_2025_window": int(len(gdp)),
        "n_wdi_population_countries_in_2020_to_2025_window": int(len(population)),
        "n_countries_in_all_three": int(len(joined)),
        "overlap_iso3": sorted(joined["iso3"].astype(str).tolist()),
        "year_spans_of_matched_observations": years,
        "unmatched_owid_iso3": sorted(
            set(poverty["iso3"]) - set(joined["iso3"])
        ),
        "known_limits": [
            "No Forbes 2026 country counts included in this step.",
            "No country-of-residence versus citizenship mapping is inferred.",
            "Observation years need not equal underlying household survey years.",
            "WDI APIs are revision-prone; files must be preserved by SHA-256.",
            "No historical growth, inequality, or causal effect is estimated.",
        ],
    }


def write_report(snapshot_dir: Path, output: Path) -> dict[str, Any]:
    """Write deterministic JSON without a machine-dependent generated timestamp."""
    report = summarize_public_sources(snapshot_dir)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return report


def main() -> None:
    """Command-line entrypoint for a checked source snapshot."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--snapshot-dir", type=Path, required=True,
        help="Directory produced by source_pipeline.py fetch",
    )
    parser.add_argument(
        "--output", type=Path, required=True,
        help="Coverage and provenance report JSON",
    )
    args = parser.parse_args()
    result = write_report(args.snapshot_dir, args.output)
    print(
        f"Validated {result['n_countries_in_all_three']} OWID/WDI "
        f"country records; report: {args.output}"
    )


if __name__ == "__main__":
    main()
