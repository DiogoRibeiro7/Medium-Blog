"""docs/DATA.md, generated from the derived tables alone. No programme is solved, and no
curve is compared with a price; price levels are not shown."""

from __future__ import annotations

import csv
import json
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from iberian_lp.contract import NON_CONVEX, SIMPLE

TOLERANCE_MW = 0.1
TYPE_NAMES = {SIMPLE: "simple", "C01": "simple block", "C02": "scalable complex",
              "C04": "exclusive block"}
ZONE_NAMES = {"MI": "Joint Iberian market", "ES": "Spain (split periods)",
              "PT": "Portugal (split periods)"}


@dataclass(frozen=True)
class Derived:
    periods: list[dict[str, str]]
    days: list[str]
    manifest: dict[str, Any]


def load(directory: Path) -> Derived:
    with (directory / "periods.csv").open(encoding="utf-8") as stream:
        periods = list(csv.DictReader(stream))
    with (directory / "days.csv").open(encoding="utf-8") as stream:
        days = [r["date"] for r in csv.DictReader(stream)]
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    return Derived(periods, days, manifest)


def f(row: dict[str, str], name: str) -> float:
    return float(row[name])


def supply(row: dict[str, str]) -> float:
    """Matched supply: accepted sell steps of every type, and imports."""
    return sum(f(row, f"matched_sell_{t}") for t in (SIMPLE, *NON_CONVEX)) + \
        f(row, "imports_fr") + f(row, "imports_ib")


def demand(row: dict[str, str]) -> float:
    return f(row, "matched_buy") + f(row, "exports_fr") + f(row, "exports_ib")


def structure(d: Derived) -> dict[str, Any]:
    """Per (date, period): which zones it has."""
    zones: dict[tuple[str, str], set[str]] = {}
    for r in d.periods:
        zones.setdefault((r["date"], r["period"]), set()).add(r["zone"])
    kinds = Counter("joint" if z == {"MI"} else "split" if z == {"ES", "PT"} else "mixed"
                    for z in zones.values())
    per_day = Counter(date for date, _ in zones)
    split_days = {date for (date, _), z in zones.items() if z == {"ES", "PT"}}
    return {"periods": len(zones), "kinds": kinds, "per_day": Counter(per_day.values()),
            "split_days": len(split_days)}


def checks(d: Derived) -> dict[str, Any]:
    by_key = {(r["date"], r["period"], r["zone"]): r for r in d.periods}
    imbalance = [abs(supply(r) - demand(r)) for r in d.periods]
    border = []
    for (date, period, zone), r in by_key.items():
        if zone == "ES":
            pt = by_key[(date, period, "PT")]
            border += [abs(f(r, "exports_ib") - f(pt, "imports_ib")),
                       abs(f(r, "imports_ib") - f(pt, "exports_ib"))]
    france = [max(abs(f(r, "imports_fr") - abs(f(r, "fr_import_occupied"))),
                  abs(f(r, "exports_fr") - abs(f(r, "fr_export_occupied"))))
              for r in d.periods if r["zone"] in ("MI", "ES")]
    joint = [r for r in d.periods if r["zone"] == "MI"]
    split = [r for r in d.periods if r["zone"] == "ES"]
    return {
        "imbalance_max": max(imbalance),
        "imbalance_over": sum(1 for x in imbalance if x > TOLERANCE_MW),
        "border_max": max(border, default=0.0),
        "border_over": sum(1 for x in border if x > TOLERANCE_MW),
        "france_max": max(france), "france_over": sum(1 for x in france if x > TOLERANCE_MW),
        "joint_same_price": sum(1 for r in joint if r["price_pt"] == r["price_es"]),
        "joint": len(joint),
        "split_different_price": sum(1 for r in split if r["price_pt"] != r["price_es"]),
        "split": len(split)}


def _q(values: list[float]) -> str:
    p = np.percentile(values, [5, 50, 95])
    return f"{p[1]:,.0f} | {p[0]:,.0f} | {p[2]:,.0f} | {max(values):,.0f}"


def render(d: Derived, command: str) -> str:
    m = d.manifest
    s, c = structure(d), checks(d)
    total_bytes = sum(x["bytes"] for x in m["files"])
    months = Counter(day[:7] for day in d.days)
    lines = [
        "# Data: OMIE's day-ahead order books", "",
        "Generated by `iberian-lp data` from the downloaded files, as sections 3 and 4 of "
        "[METHODS.md](../METHODS.md) fix them. **No programme has been solved, and no curve "
        f"has been compared with a price; price levels are not shown.** Data: {m['source']}.",
        "",
        f"- **Files:** {len(m['files'])} ({len(d.days)} days × "
        f"{len({x['kind'] for x in m['files']})} kinds), {total_bytes:,} bytes, read with "
        f"the {m['specification']}. Names, sizes and SHA-256 hashes are in "
        "`data/derived/manifest.json`; the files are not committed.",
        "- **Versions:** " + ", ".join(f"{k} {v}" for k, v in m["versions"].items()) + ".",
        f"- **Days:** {len(d.days)} from {m['period'][0]} to {m['period'][1]}, "
        f"{m['days_per_month']} in each of {len(months)} months, seed {m['days_seed']}: "
        + ", ".join(d.days) + ".", "",
        "## Periods and zones", "",
        "A period is joint when its curve rows are all MI, and split when they are ES and PT; "
        "a period with both is mixed and is left out (section 4).", "",
        "| Periods | Periods per day (days) | Joint | Split | Mixed | Days with a split |",
        "| ---: | --- | ---: | ---: | ---: | ---: |",
        f"| {s['periods']:,} | " + ", ".join(f"{n} ({k})" for n, k in
                                             sorted(s["per_day"].items()))
        + f" | {s['kinds']['joint']:,} | {s['kinds']['split']:,} | {s['kinds']['mixed']:,} "
        f"| {s['split_days']} |", "",
        f"In joint periods, the published Portuguese and Spanish prices are equal in "
        f"{c['joint_same_price']:,} of {c['joint']:,}; in split periods they differ in "
        f"{c['split_different_price']:,} of {c['split']:,}.", "",
        "## Steps per zone-period", "",
        "Offered steps as published, and after summing steps of the same side, type and "
        "price (the tables in `data/derived/steps/`).", "",
        "| Zone | Zone-periods | Offered steps: median | 5th | 95th | max | Summed by price: "
        "median | 5th | 95th | max |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for zone, name in ZONE_NAMES.items():
        rows = [r for r in d.periods if r["zone"] == zone]
        if rows:
            lines.append(f"| {name} | {len(rows):,} | "
                         f"{_q([f(r, 'steps_offered') for r in rows])} | "
                         f"{_q([f(r, 'steps_aggregated') for r in rows])} |")
    lines += ["", "## Offered and accepted volume by order type", "",
              "Summed over every zone-period, in MWh (MW over a quarter of an hour). Only "
              "sell orders carry the non-convex types.", "",
              "| Side | Type | Offered (MWh) | Share of offered sell volume | Accepted (MWh) | "
              "Share accepted |", "| --- | --- | ---: | ---: | ---: | ---: |"]
    sell_total = sum(f(r, f"offered_sell_{t}") for r in d.periods for t in TYPE_NAMES)
    for t, name in TYPE_NAMES.items():
        offered = sum(f(r, f"offered_sell_{t}") for r in d.periods)
        accepted = sum(f(r, f"matched_sell_{t}") for r in d.periods)
        lines.append(f"| Sell | {name} ({t}) | {offered / 4:,.0f} | {offered / sell_total:.2%} "
                     f"| {accepted / 4:,.0f} | {accepted / offered:.1%} |")
    offered = sum(f(r, "offered_buy") for r in d.periods)
    accepted = sum(f(r, "matched_buy") for r in d.periods)
    lines.append(f"| Buy | simple (S) | {offered / 4:,.0f} | - | {accepted / 4:,.0f} | "
                 f"{accepted / offered:.1%} |")
    spanish = [r for r in d.periods if r["zone"] in ("MI", "ES")]
    imports = [f(r, "imports_fr") for r in spanish if f(r, "imports_fr") > 0]
    exports = [f(r, "exports_fr") for r in spanish if f(r, "exports_fr") > 0]
    both = sum(1 for r in spanish if f(r, "imports_fr") > 0 and f(r, "exports_fr") > 0)
    lines += ["", "## Flows with France", "",
              f"Over the {len(spanish):,} joint or Spanish zone-periods: imports from France "
              f"in {len(imports):,} (median {np.median(imports) if imports else 0:,.0f} MW), "
              f"exports to France in {len(exports):,} (median "
              f"{np.median(exports) if exports else 0:,.0f} MW), both in {both:,}.", "",
              "## Checks", "",
              f"Each compares quantities only, with a tolerance of {TOLERANCE_MW} MW.", "",
              f"- **The matched curve balances.** In every zone-period, accepted sell volume "
              f"plus imports equals accepted buy volume plus exports: largest difference "
              f"{c['imbalance_max']:.1f} MW, {c['imbalance_over']} zone-periods over the "
              "tolerance.",
              f"- **The two sides of the Spanish-Portuguese border agree** in split periods: "
              f"largest difference {c['border_max']:.1f} MW, {c['border_over']} over.",
              f"- **The France flows in the curves match the interconnector file** "
              f"(`capacidad_inter_pbc`, border 3): largest difference {c['france_max']:.1f} MW, "
              f"{c['france_over']} zone-periods over.", "",
              "## Reproduce", "", "```", "iberian-lp download --raw data/raw", command, "```",
              ""]
    return "\n".join(lines)
