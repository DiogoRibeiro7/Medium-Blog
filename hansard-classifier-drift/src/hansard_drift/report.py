"""results/RESULTS.md: every number the article uses, in one place."""

from __future__ import annotations

import json

import pandas as pd

from .config import Config


def _f(x, nd=1) -> str:
    return "" if pd.isna(x) else f"{x:,.{nd}f}"


def _ci(row, key, nd=2) -> str:
    return f"{_f(row[f'{key}_median'], nd)} [{_f(row[f'{key}_lo'], nd)}, {_f(row[f'{key}_hi'], nd)}]"


def write_report(cfg: Config) -> str:
    s1 = cfg.stage1_dir
    lines = ["# Results", "", "Generated by `hansard-drift report`. Do not edit by hand.", ""]
    man = json.loads((s1 / "manifest.json").read_text(encoding="utf-8"))
    src = man.get("source", {})
    lines += [
        "## Corpus",
        "",
        f"- Source: `{src.get('repo_id', '?')}` at commit `{src.get('commit', '?')}`",
        f"- Rows: {man['rows']:,}, sitting days: {man['sitting_days']:,}, {man['first_date']} to {man['last_date']}",
        f"- Ids parsed for sitting order: {man['ids_parsed_share']:.4%}",
        f"- Member speeches: {man['member_speeches']:,}; Chair speeches: {man['chair_speeches']:,} "
        f"(by printed title {man['chair_by_source'].get('title', 0):,}, by post {man['chair_by_source'].get('post', 0):,})",
        f"- Chair speeches with no Member speech earlier that day: {man['chair_with_no_member_before']:,}",
        f"- Dictionary v{man['dictionary_version']}: discipline-tagged {man['discipline_tagged']:,}, "
        f"time-keeping-tagged {man['timekeeping_tagged']:,}",
        "",
        "## Naive rates (dictionary counts per 1,000 Member speeches)",
        "",
        "| Era | Discipline | Time-keeping | Opp ÷ Gov (discipline) |",
        "|---|---:|---:|---:|",
    ]
    naive = pd.read_csv(s1 / "naive_rates.csv")
    for era in cfg.era_names:
        d = naive[(naive["construct"] == "discipline") & (naive["era"] == era)].set_index("side")["rate_per_1000"]
        t = naive[(naive["construct"] == "timekeeping") & (naive["era"] == era)].set_index("side")["rate_per_1000"]
        if d.empty:
            continue
        ratio = d.get("Opposition") / d.get("Government") if d.get("Government") else float("nan")
        lines.append(f"| {era} | {_f(d['All'], 2)} | {_f(t['All'], 2)} | {_f(ratio, 2)} |")

    cats = pd.read_csv(s1 / "categories.csv")
    disc = cats[cats["family"] == "discipline"].pivot(
        index="category", columns="era", values="share_of_discipline_tagged"
    )
    disc = disc[[e for e in cfg.era_names if e in disc.columns]]
    lines += ["", "## What the discipline tag is made of (share of tagged speeches with each category)", ""]
    lines += ["| Category | " + " | ".join(disc.columns) + " |", "|---|" + "---:|" * len(disc.columns)]
    for cat, row in disc.iterrows():
        lines.append(f"| {cat} | " + " | ".join(f"{v:.1%}" for v in row) + " |")

    lf = pd.read_csv(s1 / "length_filter.csv")
    lines += ["", "## The length filter as a classifier (share removed by dropping speeches under k words)", ""]
    lines += ["| Era | k | Discipline-tagged Chair speeches | Member speeches |", "|---|---:|---:|---:|"]
    for _, r in lf.iterrows():
        lines.append(
            f"| {r['era']} | {r['min_words']} | {r['discipline_tagged_removed']:.1%} | {r['member_speeches_removed']:.1%} |"
        )

    top = pd.read_csv(s1 / "lexical_top.csv")
    lines += ["", "## Most distinctive Chair terms per era (log-odds, informative Dirichlet prior)", ""]
    for era, g in top.groupby("era", sort=False):
        terms = ", ".join(f"{t} ({z:.0f})" for t, z in zip(g["term"].head(12), g["z"].head(12), strict=True))
        lines.append(f"- **{era}**: {terms}")

    s2 = cfg.stage2_dir
    if (s2 / "summary.json").exists():
        summ = json.loads((s2 / "summary.json").read_text(encoding="utf-8"))
        tot = summ["totals"]
        lines += [
            "",
            "## Corrected estimates",
            "",
            f"Labels: `{summ['label_source']}`, {summ['labelled_items']} items; Beta({summ['prior']}, {summ['prior']}) per stratum; "
            f"{summ['draws']:,} draws. Medians with 95% intervals.",
            "",
            f"- Whole period: dictionary count {tot['tagged']:,}; estimated true interventions "
            f"{tot['interventions']['median']:,.0f} [{tot['interventions']['lo']:,.0f}, {tot['interventions']['hi']:,.0f}]; "
            f"precision {tot['precision']['median']:.3f} [{tot['precision']['lo']:.3f}, {tot['precision']['hi']:.3f}]; "
            f"recall {tot['recall']['median']:.3f} [{tot['recall']['lo']:.3f}, {tot['recall']['hi']:.3f}]",
        ]
        if summ["strata_without_labels"]:
            lines.append(f"- Strata with speeches but no labels (prior only): {summ['strata_without_labels']}")
        ce = pd.read_csv(s2 / "corrected_by_era.csv")
        lines += [
            "",
            "| Era | Naive rate | Corrected rate | Precision | Recall | P(lowest) | P(highest) |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for _, r in ce.iterrows():
            lines.append(
                f"| {r['era']}{' (partial)' if r['partial'] else ''} | {_f(r['naive_rate'], 2)} | {_ci(r, 'rate')} | "
                f"{_ci(r, 'precision', 3)} | {_ci(r, 'recall', 3)} | {_f(r['p_lowest'], 3)} | {_f(r['p_highest'], 3)} |"
            )
        dec = pd.read_csv(s2 / "decomposition.csv")
        lines += [
            "",
            f"### Decomposition against {summ['reference_era']} (log ratios; naive = true + recall + precision)",
            "",
            "| Era | Naive ratio | True ratio | log naive | log true | log recall | −log precision |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for _, r in dec.iterrows():
            lines.append(
                f"| {r['era']} | {_f(r['naive_ratio'], 3)} | {_ci(r, 'true_ratio', 3)} | {_f(r['naive_log_ratio'], 3)} | "
                f"{_ci(r, 'true', 3)} | {_ci(r, 'recall', 3)} | {_ci(r, 'precision', 3)} |"
            )
        sd = pd.read_csv(s2 / "sides.csv")
        lines += [
            "",
            "### Opposition ÷ Government",
            "",
            "| Era | Naive ratio | Corrected ratio | P(ratio > 1) | Precision Gov | Precision Opp | Recall Gov | Recall Opp |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for _, r in sd.iterrows():
            lines.append(
                f"| {r['era']} | {_f(r['naive_ratio_opp_gov'], 2)} | {_ci(r, 'ratio_opp_gov')} | {_f(r['p_ratio_above_1'], 3)} | "
                f"{_ci(r, 'Government_precision', 2)} | {_ci(r, 'Opposition_precision', 2)} | "
                f"{_ci(r, 'Government_recall', 2)} | {_ci(r, 'Opposition_recall', 2)} |"
            )
    if (s2 / "transfer.csv").exists():
        tr = pd.read_csv(s2 / "transfer.csv")
        lines += [
            "",
            "## Dictionary against a learned classifier",
            "",
            "| Era | Method | Precision | Recall |",
            "|---|---|---:|---:|",
        ]
        for _, r in tr.iterrows():
            lines.append(
                f"| {r['era']} | {r['method']} | {r['precision']:.3f} [{r['precision_lo']:.3f}, {r['precision_hi']:.3f}] | "
                f"{r['recall']:.3f} [{r['recall_lo']:.3f}, {r['recall_hi']:.3f}] |"
            )
    agr = cfg.labels_dir / "agreement.csv"
    if agr.exists():
        a = pd.read_csv(agr)
        lines += ["", "## Agreement between annotators", ""]
        for _, r in a.iterrows():
            lines.append(
                f"- {r['annotator_a']} vs {r['annotator_b']}: {r['items']} items, raw agreement {r['raw_agreement']:.3f}, "
                f"Cohen's kappa {r['kappa']:.3f}"
            )
    path = cfg.root / "results" / "RESULTS.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return str(path)
